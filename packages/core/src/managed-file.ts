import { Construct } from 'constructs';
import { existsSync, readFileSync } from 'node:fs';
import { join } from 'node:path';
import { parse as parseYaml, stringify as stringifyYaml } from 'yaml';

export const GENERATED_HEADER = '# Generated by cikick — do not edit. Run `npx cikick synth`.';

export type ManagedFileMode = 'managed' | 'seeded' | 'merged';
export type ManagedFileFormat = 'yaml' | 'json' | 'text';

export interface ManagedFileProps {
  /** Path relative to repo root. */
  path: string;
  mode: ManagedFileMode;
  content: object | string;
  format?: ManagedFileFormat;
  /** Repo-owned file (relative to repo root) deep-merged over `content` in `merged` mode. */
  patchFile?: string;
}

const BRAND = Symbol.for('@cikick/core.ManagedFile');

/** Deep merge: objects merge recursively, arrays/scalars are replaced, `null` in the patch deletes the key. */
export function deepMerge(base: unknown, patch: unknown): unknown {
  const isObj = (v: unknown): v is Record<string, unknown> => !!v && typeof v === 'object' && !Array.isArray(v);
  if (!isObj(base) || !isObj(patch)) return patch;
  const out: Record<string, unknown> = { ...base };
  for (const [k, v] of Object.entries(patch)) {
    if (v === null) delete out[k];
    else out[k] = k in out ? deepMerge(out[k], v) : v;
  }
  return out;
}

function inferFormat(path: string, content: object | string): ManagedFileFormat {
  if (/\.json$/i.test(path)) return 'json';
  if (/\.ya?ml$/i.test(path)) return 'yaml';
  return typeof content === 'string' ? 'text' : 'json';
}

export class ManagedFile extends Construct {
  static isManagedFile(x: unknown): x is ManagedFile {
    return typeof x === 'object' && x !== null && (x as any)[BRAND] === true;
  }
  readonly [BRAND] = true;
  readonly path: string;
  readonly mode: ManagedFileMode;
  readonly content: object | string;
  readonly format: ManagedFileFormat;
  readonly patchFile?: string;

  constructor(scope: Construct, id: string, props: ManagedFileProps) {
    super(scope, id);
    this.path = props.path.replace(/\\/g, '/').replace(/^\.\//, '');
    this.mode = props.mode;
    this.content = props.content;
    this.format = props.format ?? inferFormat(props.path, props.content);
    this.patchFile = props.patchFile;
  }

  /** Render final file content. `repoDir` is used to read `patchFile` in merged mode. */
  render(repoDir: string): string {
    const fmt = this.format;
    if (fmt === 'text') {
      if (this.mode === 'merged') throw new Error(`ManagedFile ${this.path}: merged mode requires json or yaml format`);
      if (typeof this.content !== 'string') throw new Error(`ManagedFile ${this.path}: text format requires string content`);
      return this.content;
    }
    let data: unknown = typeof this.content === 'string' ? (fmt === 'json' ? JSON.parse(this.content) : parseYaml(this.content)) : this.content;
    if (this.mode === 'merged' && this.patchFile) {
      const p = join(repoDir, this.patchFile);
      if (existsSync(p)) {
        const raw = readFileSync(p, 'utf8');
        let patch: unknown;
        try {
          patch = fmt === 'json' ? JSON.parse(raw) : parseYaml(raw);
        } catch (e) {
          throw new Error(`ManagedFile ${this.path}: cannot parse patchFile ${this.patchFile}: ${(e as Error).message}`);
        }
        data = deepMerge(data, patch);
      }
    }
    if (fmt === 'json') return JSON.stringify(data, null, 2) + '\n';
    const body = stringifyYaml(data, { lineWidth: 0 });
    return this.mode === 'seeded' ? body : `${GENERATED_HEADER}\n${body}`;
  }
}
