import { mkdirSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { describe, expect, it } from 'vitest';
import { App, ManagedFile, checkDrift, deepMerge, secret, secretsManifest, synth, writeSynthResult, Workflow } from '../src/index.js';
import { tmp } from './helpers.js';

describe('managed files', () => {
  it('managed: overwritten and drift detected', async () => {
    const dir = tmp();
    const mk = (v: number) => {
      const app = new App();
      new ManagedFile(app, 'f', { path: 'config/a.json', mode: 'managed', content: { v } });
      return app;
    };
    const r1 = await synth(mk(1), { repoDir: dir });
    writeSynthResult(r1, dir);
    expect(readFileSync(join(dir, 'config/a.json'), 'utf8')).toBe('{\n  "v": 1\n}\n');
    expect(checkDrift(r1, dir)).toEqual([]);
    writeFileSync(join(dir, 'config/a.json'), 'tampered');
    expect(checkDrift(r1, dir)).toEqual(['config/a.json']);
    const r2 = await synth(mk(2), { repoDir: dir });
    writeSynthResult(r2, dir);
    expect(readFileSync(join(dir, 'config/a.json'), 'utf8')).toContain('"v": 2');
  });

  it('seeded: written once, never overwritten, no drift', async () => {
    const dir = tmp();
    const app = new App();
    new ManagedFile(app, 's', { path: 'seed.yml', mode: 'seeded', content: { a: 1 } });
    const r = await synth(app, { repoDir: dir });
    expect(checkDrift(r, dir)).toContain('seed.yml');
    const w1 = writeSynthResult(r, dir);
    expect(w1.written).toContain('seed.yml');
    writeFileSync(join(dir, 'seed.yml'), 'mine: true\n');
    expect(checkDrift(r, dir)).not.toContain('seed.yml');
    const w2 = writeSynthResult(r, dir);
    expect(w2.skipped).toEqual(['seed.yml']);
    expect(readFileSync(join(dir, 'seed.yml'), 'utf8')).toBe('mine: true\n');
  });

  it('merged: deep merges patchFile (json and yaml)', async () => {
    const dir = tmp();
    mkdirSync(join(dir, '.cikick'));
    writeFileSync(join(dir, '.cikick/tsconfig.patch.json'), JSON.stringify({ compilerOptions: { strict: false, target: 'ES2022' }, extra: [1], gone: null }));
    writeFileSync(join(dir, '.cikick/lint.patch.yml'), 'rules:\n  b: 2\n');
    const app = new App();
    new ManagedFile(app, 'j', { path: 'tsconfig.json', mode: 'merged', patchFile: '.cikick/tsconfig.patch.json', content: { compilerOptions: { strict: true, module: 'nodenext' }, gone: 1 } });
    new ManagedFile(app, 'y', { path: 'lint.yml', mode: 'merged', patchFile: '.cikick/lint.patch.yml', content: { rules: { a: 1 } } });
    new ManagedFile(app, 'n', { path: 'nopatch.json', mode: 'merged', patchFile: 'missing.json', content: { a: 1 } });
    const r = await synth(app, { repoDir: dir });
    const by = Object.fromEntries(r.files.map((f) => [f.path, f]));
    expect(JSON.parse(by['tsconfig.json']!.content)).toEqual({ compilerOptions: { strict: false, module: 'nodenext', target: 'ES2022' }, extra: [1] });
    expect(by['lint.yml']!.content).toBe('# Generated by cikick — do not edit. Run `npx cikick synth`.\nrules:\n  a: 1\n  b: 2\n');
    expect(JSON.parse(by['nopatch.json']!.content)).toEqual({ a: 1 });
    expect(by['tsconfig.json']!.mode).toBe('merged');
  });

  it('deepMerge replaces arrays', () => {
    expect(deepMerge({ a: [1, 2], b: { c: 1 } }, { a: [3], b: { d: 2 } })).toEqual({ a: [3], b: { c: 1, d: 2 } });
  });

  it('text files pass through', async () => {
    const app = new App();
    new ManagedFile(app, 't', { path: 'x.txt', mode: 'managed', content: 'hello\n' });
    expect((await synth(app, { repoDir: tmp() })).files[0]!.content).toBe('hello\n');
  });
});

describe('secrets', () => {
  it('secret() returns expression and registers one decl', () => {
    const app = new App();
    const wf = new Workflow(app, 'ci', { on: 'push' });
    const j = wf.addJob('j', {});
    expect(secret(j, 'NPM_TOKEN', { maxAgeDays: 90, provider: 'npm' })).toBe('${{ secrets.NPM_TOKEN }}');
    secret(wf, 'NPM_TOKEN');
    secret(wf, 'DEPLOY_KEY', { scope: 'env', environment: 'prod' });
    expect(secretsManifest(app)).toEqual([
      { name: 'DEPLOY_KEY', scope: 'env', environment: 'prod' },
      { name: 'NPM_TOKEN', scope: 'repo', maxAgeDays: 90, provider: 'npm' },
    ]);
  });
});
