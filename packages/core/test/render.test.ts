import { describe, expect, it } from 'vitest';
import { App, Workflow, synth, ActionRef } from '../src/index.js';
import { FakeResolver, SHA, tmp } from './helpers.js';

function build() {
  const app = new App();
  const wf = new Workflow(app, 'ci', {
    name: 'CI',
    on: { push: { branches: ['main'] }, pullRequest: null, workflowDispatch: { inputs: { x: { type: 'string' } } } },
    permissions: { contents: 'read', idToken: 'write' },
    concurrency: { group: 'ci-${{ github.ref }}', cancelInProgress: true },
    env: { CI: '1' },
  });
  const test = wf.addJob('test', {
    runsOn: 'ubuntu-latest',
    timeoutMinutes: 10,
    strategy: { matrix: { node: [20, 22] }, failFast: false },
  });
  test.addStep({ uses: 'actions/checkout@v4' });
  test.addStep({ run: 'npm ci\nnpm test', name: 'Test' });
  wf.addJob('deploy', { needs: test, runsOn: ['self-hosted'], environment: 'prod' }).addStep({ run: 'echo hi' });
  return { app, wf };
}

describe('rendering', () => {
  it('toObject uses kebab-case and stable key order', () => {
    const { wf } = build();
    const o = wf.toObject() as any;
    expect(Object.keys(o)).toEqual(['name', 'on', 'permissions', 'concurrency', 'env', 'jobs']);
    expect(o.on).toEqual({
      push: { branches: ['main'] },
      pull_request: {},
      workflow_dispatch: { inputs: { x: { type: 'string' } } },
    });
    expect(o.permissions).toEqual({ contents: 'read', 'id-token': 'write' });
    expect(o.concurrency).toEqual({ group: 'ci-${{ github.ref }}', 'cancel-in-progress': true });
    expect(o.jobs.test['runs-on']).toBe('ubuntu-latest');
    expect(o.jobs.test['timeout-minutes']).toBe(10);
    expect(o.jobs.test.strategy).toEqual({ matrix: { node: [20, 22] }, 'fail-fast': false });
    expect(o.jobs.deploy.needs).toBe('test');
    expect(o.jobs.test.steps[0].uses).toBe('actions/checkout@v4');
  });

  it('synth renders header, pinned sha and ref comment', async () => {
    const { app } = build();
    const res = await synth(app, {
      repoDir: tmp(),
      resolver: new FakeResolver(),
      now: new Date('2026-01-01T00:00:00Z'),
    });
    expect(res.files.map((f) => f.path)).toEqual(['.github/workflows/ci.yml']);
    const y = res.files[0]!.content;
    expect(y.startsWith('# Generated by cikick — do not edit. Run `npx cikick synth`.\n')).toBe(true);
    expect(y).toContain(`uses: actions/checkout@${SHA('a')} # v4`);
    expect(y).toContain('runs-on: ubuntu-latest');
    expect(y).toContain('timeout-minutes: 10');
    expect(y).toMatch(/run: \|-?\n\s+npm ci\n\s+npm test/);
    expect(y.indexOf('name: CI')).toBeLessThan(y.indexOf('on:'));
    expect(y.indexOf('permissions:')).toBeLessThan(y.indexOf('jobs:'));
    expect(res.lock.actions['actions/checkout@v4']).toEqual({ sha: SHA('a'), resolvedAt: '2026-01-01T00:00:00.000Z' });
  });

  it('output is deterministic', async () => {
    const a = await synth(build().app, { repoDir: tmp(), resolver: new FakeResolver() });
    const b = await synth(build().app, { repoDir: tmp(), resolver: new FakeResolver() });
    expect(a.files).toEqual(b.files);
  });

  it('reusable workflow call job', async () => {
    const app = new App();
    const wf = new Workflow(app, 'call', { on: 'push' });
    wf.addJob('r', { uses: 'acme/wf/.github/workflows/x.yml@v1', with: { a: 1 }, secrets: 'inherit' });
    wf.addJob('local', { uses: './.github/workflows/y.yml' });
    const res = await synth(app, { repoDir: tmp(), resolver: new FakeResolver() });
    const y = res.files[0]!.content;
    expect(y).toContain(`uses: acme/wf/.github/workflows/x.yml@${SHA('a')} # v1`);
    expect(y).toContain('uses: ./.github/workflows/y.yml');
    expect(y).toContain('secrets: inherit');
  });

  it('ActionRef parsing', () => {
    const r = ActionRef.of('a/b/sub/dir@v1');
    expect([r.owner, r.repo, r.path, r.ref, r.sha]).toEqual(['a', 'b', 'sub/dir', 'v1', undefined]);
    expect(ActionRef.of(`a/b@${SHA('c')}`).sha).toBe(SHA('c'));
    expect(() => ActionRef.of('nope')).toThrow();
  });
});
